import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateSeo } from './seo.mjs';
import { generateBranchEntries } from './branch-entrypoints.mjs';

const directory = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(directory, '../../site/vendor');
await mkdir(output, { recursive: true });
const result = await build({
  absWorkingDir: directory,
  entryPoints: ['entry.mjs'],
  outfile: path.join(output, 'converter-deps.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  metafile: true,
  legalComments: 'inline',
  banner: { js: '/* Generated by tools/site-converter/build.mjs. See THIRD_PARTY_LICENSES.txt. */' },
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  const parts = input.split('node_modules/');
  const nameParts = parts.at(-1).split('/');
  const name = nameParts[0].startsWith('@') ? nameParts.slice(0, 2).join('/') : nameParts[0];
  packages.add(path.resolve(directory, `${parts.slice(0, -1).join('node_modules/')}node_modules/${name}`));
}
const notices = [];
for (const dir of [...packages].sort()) {
  const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
  let license;
  for (const filename of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE']) {
    try { license = await readFile(path.join(dir, filename), 'utf8'); break; } catch { /* try next */ }
  }
  if (!license) throw new Error(`Missing license text for ${pkg.name}`);
  notices.push(`${pkg.name} ${pkg.version} (${pkg.license})\n${license}`);
}
await writeFile(path.join(output, 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n----------------------------------------\n\n'));
console.log(`Bundled browser dependencies and ${packages.size} license notices.`);
await generateSeo();
await generateBranchEntries();
